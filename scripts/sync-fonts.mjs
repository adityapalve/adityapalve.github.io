#!/usr/bin/env node
// Build the web fonts into public/fonts from the copies installed on this machine.
//
// Paper Mono is SIL OFL, so its woff2 is committed and this only refreshes it.
// ABC Areal is free from Dinamo, but their licence forbids putting the binaries in public
// repositories or on public servers. So its subset is written to public/fonts/areal/, which is
// gitignored: it renders locally and the deployed site falls back to Helvetica/Arial, which is
// what Areal is a redraw of. See the Fonts section of the README.

import { execFile } from 'node:child_process';
import { copyFile, mkdir, stat, writeFile } from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { promisify } from 'node:util';

const run = promisify(execFile);

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

const fontsRoot = path.join(repoRoot, 'public/fonts');

const paperMonoRelease = process.env.PAPER_MONO_DIR ?? path.join(os.homedir(), 'fonts/paper-mono-v1.000');

const arealSource = process.env.AREAL_FONT ?? path.join(os.homedir(), 'Library/Fonts/ABCArealVariable.ttf');

// Latin, plus the punctuation, arrows and symbols the pages use in body text.
const subsetRanges = [
  'U+0000-00FF',
  'U+0131',
  'U+0152-0153',
  'U+02BB-02BC',
  'U+02C6',
  'U+02DA',
  'U+02DC',
  'U+0300-0304',
  'U+0308-0309',
  'U+0323',
  'U+0329',
  'U+2000-206F',
  'U+2074',
  'U+20AC',
  'U+2122',
  'U+2190-21BB',
  'U+2200-22FF',
  'U+25A0-25CF',
  'U+2600-26FF',
  'U+2700-27BF',
  'U+FEFF',
  'U+FFFD',
].join(',');

// The proportional cut carries the body text; the mono cut is left out because Paper Mono has it.
const arealFace = `/* Generated by scripts/sync-fonts.mjs in a gitignored folder — see the README. */
@font-face {
  font-family: 'ABC Areal';
  src: url('/fonts/areal/ABC-Areal-Variable.woff2') format('woff2');
  font-weight: 400 700;
  font-style: normal;
  font-display: swap;
}

@font-face {
  font-family: 'ABC Areal';
  src: url('/fonts/areal/ABC-Areal-Variable.woff2') format('woff2');
  font-weight: 400 700;
  font-style: oblique 0deg 12deg;
  font-display: swap;
}
`;

function relative(filePath) {
  return path.relative(repoRoot, filePath);
}

async function modifiedAt(filePath) {
  const info = await stat(filePath).catch(() => undefined);

  return info === undefined ? 0 : info.mtimeMs;
}

/** Missing or older than its source, so the copy is worth redoing. */
async function isStale(source, target) {
  return (await modifiedAt(target)) < (await modifiedAt(source));
}

async function exists(filePath) {
  return (await modifiedAt(filePath)) > 0;
}

async function syncPaperMono() {
  const source = path.join(paperMonoRelease, 'fonts/webfonts/PaperMono[wght].woff2');
  const target = path.join(fontsRoot, 'paper-mono/PaperMono-Variable.woff2');

  if (!(await exists(source))) {
    console.log(`keep  ${relative(target)}: no Paper Mono release at ${paperMonoRelease}`);

    return;
  }

  await mkdir(path.dirname(target), { recursive: true });
  await copyFile(source, target);
  await copyFile(path.join(paperMonoRelease, 'OFL.txt'), path.join(fontsRoot, 'paper-mono/OFL.txt'));
  console.log(`sync  ${relative(target)} (SIL OFL, committed)`);
}

async function syncAreal() {
  const target = path.join(fontsRoot, 'areal/ABC-Areal-Variable.woff2');
  const face = path.join(fontsRoot, 'areal/areal.css');

  if (!(await exists(arealSource))) {
    console.log(`skip  ABC Areal: no font at ${arealSource}`);
    console.log('      download it from https://abcdinamo.com/free/areal, then re-run npm run fonts:sync');

    return;
  }

  await mkdir(path.dirname(target), { recursive: true });

  if (await isStale(arealSource, target)) {
    try {
      await run('python3', [
        '-m',
        'fontTools.subset',
        arealSource,
        `--output-file=${target}`,
        '--flavor=woff2',
        `--unicodes=${subsetRanges}`,
        '--layout-features=*',
        '--no-hinting',
      ]);
    } catch (error) {
      console.warn(`skip  ABC Areal: subsetting failed. ${messageOf(error)}`);
      console.warn('      needs Python with: pip install fonttools brotli');

      return;
    }

    console.log(`sync  ${relative(target)} (gitignored, local only)`);
  }

  await writeFile(face, arealFace);
}

function messageOf(error) {
  return error instanceof Error ? error.message : String(error);
}

async function main() {
  await syncPaperMono();
  await syncAreal();
}

// This runs from `predev`, so a missing Python or a locked file should not stop the dev server.
try {
  await main();
} catch (error) {
  console.warn(`skip  fonts: ${messageOf(error)}`);
}
